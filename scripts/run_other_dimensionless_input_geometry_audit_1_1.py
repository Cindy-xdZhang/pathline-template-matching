def _require(condition: object, message: str) -> None:
    if not condition:
        raise ValueError(message)


def _lower_hex(value: object, length: int = 64) -> bool:
    return (
        isinstance(value, str)
        and len(value) == length
        and all(character in "0123456789abcdef" for character in value)
    )


def sha256_file(path: str | Path, chunk_bytes: int = 8 * 1024 * 1024) -> str:
    digest = hashlib.sha256()
    with Path(path).open("rb") as source:
        while block := source.read(chunk_bytes):
            digest.update(block)
    return digest.hexdigest()


def _canonical_json_sha256(value: Any) -> str:
    payload = json.dumps(
        value,
        ensure_ascii=False,
        sort_keys=True,
        separators=(",", ":"),
        allow_nan=False,
    ).encode("utf-8")
    return hashlib.sha256(payload).hexdigest()


def _json_safe(value: Any) -> Any:
    if isinstance(value, Mapping):
        return {str(key): _json_safe(item) for key, item in value.items()}
    if isinstance(value, (tuple, list)):
        return [_json_safe(item) for item in value]
    if isinstance(value, (np.bool_, bool)):
        return bool(value)
    if isinstance(value, (np.integer, int)):
        return int(value)
    if isinstance(value, (np.floating, float)):
        numeric = float(value)
        _require(np.isfinite(numeric), "JSON artifact contains NaN or infinity")
        return numeric
    if isinstance(value, Path):
        return str(value)
    return value


def _manifest_with_self_hash(payload: Mapping[str, Any]) -> dict[str, Any]:
    output = dict(_json_safe(payload))
    _require("content_sha256" not in output, "manifest already contains a self hash")
    output["content_sha256"] = _canonical_json_sha256(output)
    return output


def authenticate_self_hash(payload: Mapping[str, Any]) -> None:
    content = dict(payload)
    observed = content.pop("content_sha256", None)
    _require(_lower_hex(observed), "manifest self hash is missing")
    _require(observed == _canonical_json_sha256(content), "manifest self hash mismatch")


