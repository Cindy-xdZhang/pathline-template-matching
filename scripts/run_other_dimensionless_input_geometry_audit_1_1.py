def run(
    config_path: str | Path,
    output_directory: str | Path,
    *,
    expected_git_commit: str,
) -> Mapping[str, Any]:
    plan = load_plan(config_path)
    observed_commit, dirty = _git_identity()
    _require(not dirty, "geometry audit requires a clean committed worktree")
    _require(observed_commit == expected_git_commit, "checkout commit differs from expected commit")
    def require_final_clean_identity() -> None:
        final_commit, final_dirty = _git_identity()
        _require(
            not final_dirty and final_commit == observed_commit,
            "commit or clean worktree changed before completion publication",
        )

    result = run_audit(
        plan,
        output_directory,
        git_commit=observed_commit,
        completion_guard=require_final_clean_identity,
    )
    return result


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", default=str(CONFIG_PATH))
    parser.add_argument("--output-dir", required=True)
    parser.add_argument("--expected-git-commit", required=True)
    return parser


def main(argv: Sequence[str] | None = None) -> None:
    arguments = _parser().parse_args(argv)
    result = run(
        arguments.config,
        arguments.output_dir,
        expected_git_commit=arguments.expected_git_commit,
    )
    print(
        json.dumps(
            {
                "status": result["summary"]["status"],
                "hypothesis_status": result["summary"]["rounding_envelope"][
                    "hypothesis_status"
                ],
                "counts": result["summary"]["counts"],
                "summary_file_sha256": result["summary_file_sha256"],
                "completion_file_sha256": result["completion_file_sha256"],
                "output_directory": result["output_directory"],
            },
            sort_keys=True,
            allow_nan=False,
        )
    )


if __name__ == "__main__":
    main()
